/**
 * Strukturtyp des Katalogs (Schluesselbaum wie in en.ts, aber mit
 * aufgeweiteten String-Werten). Die deutsche Katalogdatei wird damit per
 * `satisfies Messages` auf denselben Baum gezwungen, ohne dass deutsche
 * Literalwerte gegen englische Literale geprueft werden muessten.
 */
type DeepWiden<T> = { [K in keyof T]: T[K] extends string ? string : DeepWiden<T[K]> };

export type Messages = DeepWiden<typeof en>;
